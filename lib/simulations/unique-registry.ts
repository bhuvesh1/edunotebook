// lib/simulations/unique-registry.ts
// Maps topicId → unique 3D sim component (1 topic = 1 unique model).
// Each topic with a unique sim gets its own bespoke React Three Fiber component
// in app/components/sims/unique/Topic{id}Sim.tsx.
//
// The component module must export:
//   - {Topic{id}Sim}: the sim component (follows SimProps pattern)
//   - UNIQUE_CONTROLS: ControlSpec[] for the control panel
//   - UNIQUE_META: { title: string; blurb: string }

import type { ControlSpec } from "./registry";

/** Check if a topic has a unique 3D model. */
export function hasUniqueSim(topicId: number): boolean {
  return UNIQUE_TOPIC_IDS.has(topicId);
}

/**
 * Dynamically import the unique sim for a topic.
 * Returns null if the topic has no unique sim.
 */
export async function loadUniqueSim(topicId: number): Promise<{
  Component: React.ComponentType<Record<string, number | string>>;
  controls: ControlSpec[];
  meta: { title: string; blurb: string };
} | null> {
  if (!UNIQUE_TOPIC_IDS.has(topicId)) return null;
  try {
    const mod = await import(
      `../../app/components/sims/unique/Topic${topicId}Sim`
    );
    const componentName = `Topic${topicId}Sim`;
    return {
      Component: mod[componentName],
      controls: mod.UNIQUE_CONTROLS ?? [],
      meta: mod.UNIQUE_META ?? { title: "Interactive 3D", blurb: "" },
    };
  } catch {
    return null;
  }
}

